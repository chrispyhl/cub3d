#!/bin/bash

# Configuration
EXEC="./cub3D"
INVALID_DIR="maps/invalid"
VALID_DIR="maps/valid"
LOG_FILE="test_output.log"

# Valgrind Command setup
# --error-exitcode=42 allows the script to detect leaks programmatically
VALGRIND="valgrind --suppressions=./ignore.supp -s --leak-check=full --show-leak-kinds=all --error-exitcode=42"

# Text Colors
GREEN='\033[0;32m'
RED='\033[0;31m'
YELLOW='\033[0;33m'
CYAN='\033[0;36m'
NC='\033[0m'

# Check if executable exists
if [ ! -f "$EXEC" ]; then
    echo -e "${RED}Error: Executable $EXEC not found. Run 'make' first.${NC}"
    exit 1
fi

echo -e "${CYAN}========================================${NC}"
echo -e "${CYAN}   cub3D Map & Memory Leak Tester       ${NC}"
echo -e "${CYAN}========================================${NC}\n"

# ---------------------------------------------------------
# INVALID MAPS (Expected to fail cleanly with no leaks)
# ---------------------------------------------------------
echo -e "${YELLOW}=== Testing INVALID Maps ===${NC}"
echo -e "Expectation: Exit with error, no memory leaks.\n"

for map in "$INVALID_DIR"/*.cub; do
    [ -e "$map" ] || continue 

    # Run Valgrind and capture ALL output to the log file
    $VALGRIND $EXEC "$map" > "$LOG_FILE" 2>&1
    EXIT_CODE=$?

    if [ $EXIT_CODE -eq 42 ]; then
        printf "${RED}[LEAK]${NC} %-35s\n" "$(basename "$map")"
        echo -e "${YELLOW}--- Terminal Output ---${NC}"
        cat "$LOG_FILE"
        echo -e "${YELLOW}-----------------------${NC}\n"
    elif [ $EXIT_CODE -eq 0 ]; then
        printf "${RED}[FAIL]${NC} %-35s (Map was accepted but shouldn't be!)\n" "$(basename "$map")"
        echo -e "${YELLOW}--- Terminal Output ---${NC}"
        cat "$LOG_FILE"
        echo -e "${YELLOW}-----------------------${NC}\n"
    else
        printf "${GREEN}[OK]${NC}   %-35s (Rejected correctly)\n" "$(basename "$map")"
        # --- NEW: Print the error output generated by your program ---
        echo -e "${CYAN}--- Your Error Message ---${NC}"
        # grep -v filters out Valgrind's output so you only see your own print statements
        cat "$LOG_FILE" | grep -v "^==" 
        echo -e "${CYAN}--------------------------${NC}\n"
    fi
done

echo ""

# ---------------------------------------------------------
# VALID MAPS (Expected to pass cleanly with no leaks)
# ---------------------------------------------------------
echo -e "${YELLOW}=== Testing VALID Maps ===${NC}"
echo -e "Expectation: Launch successfully, close with 0 leaks."
echo -e "${RED}NOTE:${NC} Valgrind will make the game run very slowly. Close the window (ESC or X) to proceed.\n"

for map in "$VALID_DIR"/*.cub; do
    [ -e "$map" ] || continue

    echo -ne "Testing: ${CYAN}$(basename "$map")${NC}... "
    
    # Run Valgrind and capture output. The MLX window will still open normally.
    $VALGRIND $EXEC "$map" > "$LOG_FILE" 2>&1
    EXIT_CODE=$?

    if [ $EXIT_CODE -eq 42 ]; then
        echo -e "${RED}[LEAK DETECTED]${NC}"
        echo -e "${YELLOW}--- Terminal Output ---${NC}"
        cat "$LOG_FILE"
        echo -e "${YELLOW}-----------------------${NC}\n"
    elif [ $EXIT_CODE -eq 0 ]; then
        echo -e "${GREEN}[OK] (Clean exit)${NC}"
    else
        echo -e "${RED}[FAIL] (Crashed or rejected valid map)${NC}"
        echo -e "${YELLOW}--- Terminal Output ---${NC}"
        cat "$LOG_FILE"
        echo -e "${YELLOW}-----------------------${NC}\n"
    fi
done

# Cleanup
rm -f "$LOG_FILE"

echo -e "\n${CYAN}========================================${NC}"
echo -e "${CYAN}              Tests Finished            ${NC}"
echo -e "${CYAN}========================================${NC}"
