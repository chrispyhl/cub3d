#include "engine.h"

void	draw_game(t_engine *engine)
{
	int	x;
	int	y;

	x = 0;
	while (x < WIDTH)
	{
		y = 0;
		while (y < HEIGHT)
		{
			
			y++;
		}
		x++;
	}
}
